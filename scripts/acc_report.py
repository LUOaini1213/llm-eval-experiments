"""E5: validate the rubric assessments and write results/accreditation/scores.json and scores.md.

    python scripts/acc_report.py                      # validate and total (what CI runs)
    python scripts/acc_report.py --sources DIR        # also check every quotation against the source PDFs' text

DIR holds the source PDFs (not redistributed here). Their SHA-256 must match data/accreditation/assessments.json,
and `pdftotext` (poppler) must be on PATH. A quotation passes if every fragment appears on the stated page.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from evalab import accreditation as AC  # noqa: E402

DATA = ROOT / "data" / "accreditation"
OUT = ROOT / "results" / "accreditation"


def pages(pdf: Path) -> list[str]:
    text = subprocess.run(["pdftotext", "-raw", str(pdf), "-"], capture_output=True, check=True).stdout.decode("utf-8", "replace")
    return text.split("\f")


def check_quotes(assess: dict, src: Path) -> list[str]:
    problems = []
    by_hash = {hashlib.sha256(p.read_bytes()).hexdigest(): p for p in src.glob("*.pdf")}
    for rep in assess["reports"]:
        pdf = by_hash.get(rep["sha256"])
        if pdf is None:
            problems.append(f"{rep['id']}: no PDF with SHA-256 {rep['sha256'][:12]} in {src}")
            continue
        pg = pages(pdf)
        for k, s in rep["scores"].items():
            if s.get("quote") and not AC.quote_found(s["quote"], pg[s["page"] - 1]):
                problems.append(f"{rep['id']} {k}: quotation not found on p. {s['page']}")
    return problems


def table(rubric: dict, assess: dict, tot: dict) -> str:
    reps = assess["reports"]
    lines = ["| Indicator | " + " | ".join(r["id"] for r in reps) + " |", "|---|" + "---|" * len(reps)]
    for c in rubric["criteria"]:
        for i in c["indicators"]:
            mark = " (critical)" if i["critical"] else ""
            lines.append(f"| {i['id']} {i['short']}{mark} | "
                         + " | ".join(str(r["scores"][i["id"]]["score"]) for r in reps) + " |")
        lines.append(f"| **{c['id']} {c['name']}** | "
                     + " | ".join(f"**{tot[r['id']][c['id']]['score']} / {tot[r['id']][c['id']]['max']}**" for r in reps) + " |")
    lines.append("| **Total** | " + " | ".join(f"**{tot[r['id']]['total']['score']} / {tot[r['id']]['total']['max']}**"
                                              for r in reps) + " |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sources", type=Path)
    args = ap.parse_args()
    rubric = json.loads((DATA / "rubric.json").read_text(encoding="utf-8"))
    assess = json.loads((DATA / "assessments.json").read_text(encoding="utf-8"))
    problems = [p for rep in assess["reports"] for p in AC.validate(rubric, rep)]
    if args.sources:
        problems += check_quotes(assess, args.sources)
    if problems:
        raise SystemExit("\n".join(problems))
    tot = {r["id"]: AC.totals(rubric, r) for r in assess["reports"]}
    gaps = {r["id"]: AC.critical_gaps(rubric, r) for r in assess["reports"]}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "scores.json").write_text(json.dumps({"totals": tot, "critical_gaps": gaps}, indent=1) + "\n",
                                     encoding="utf-8", newline="\n")
    md = ["# Rubric scores (generated by scripts/acc_report.py)", "",
          "\n".join(f"- **{r['id']}**: {r['title']}" for r in assess["reports"]), "", table(rubric, assess, tot),
          "Critical indicators at 0 (evidence requested before the report can be relied on):", ""]
    md += [f"- {rid}: {', '.join(g) if g else 'none'}" for rid, g in gaps.items()]
    (OUT / "scores.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps({k: v["total"] for k, v in tot.items()}), gaps)
    if args.sources:
        print("all quotations found on their stated pages")


if __name__ == "__main__":
    main()
